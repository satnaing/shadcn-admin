/**
 * ASCII kebab preview of the English slug the API stores on every locale row.
 * Non-Latin titles should not drive URLs — editors set the slug from EN.
 */
export function slugify(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}
